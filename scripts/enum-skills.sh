#!/bin/zsh
# Per-skill enumeration across the four skill roots OMP reads on this machine.
# Output: $1 or .tmp/phase2/plumb-F-skills.md  (Plumb, 2026-09-22; source of INVENTORY.md § 8)
set -u
OUT=${1:-/Users/jowolff/code/agent-system-2.0/.tmp/phase2/plumb-F-skills.md}
P=/Users/jowolff/.claude/plugins/cache/contextpress/newdle/0.2.171
typeset -A ROOTS PRIO
ROOTS=(omp /Users/jowolff/.omp/agent/skills claude /Users/jowolff/.claude/skills plugin $P/skills claudex /Users/jowolff/.claude/plugins/cache/claudex-loop/claudex-loop/2.1.0/skills agents /Users/jowolff/.agents/skills)
PRIO=(omp 100 claude 80 plugin 70 claudex 70 agents 70)
ORDER=(omp claude plugin claudex agents)

# Plumb's own <skills> block, copied from this seat's system prompt (89 names).
BLOCK=(api-and-interface-design bb-cli browser-testing-with-devtools canary careful ci-cd-and-automation claudex-loop claudex-route code-review code-review-and-quality code-simplification codebase-design codex-build codex-review context-engineering council create-skill ctx debugging-and-error-recovery deprecation-and-migration diagnosing-bugs documentation-and-adrs domain-modeling doubt-driven-development frontend-ui-engineering gaslight git-guardrails-claude-code git-workflow-and-versioning grilling humanizer idea-refine impeccable incremental-implementation interview-me jo-deck linear-project-suggest migrate-to-shoehorn new-seat newdle-a11y-audit newdle-audits newdle-code-review newdle-code-simplify newdle-cso newdle-eval-authoring newdle-land-and-deploy newdle-nightly-prioritize newdle-nightly-recap newdle-performance-audit newdle-project-plan newdle-project-spec newdle-project-sync newdle-qa newdle-responsive-audit newdle-security-audit newdle-seo-audit newdle-smoke-test newdle-storybook-stories newdle-sync-product-docs newdle-triple-check newdle-voice observability-and-instrumentation orchestrator-evals peon-ping-config peon-ping-log peon-ping-toggle peon-ping-use performance-optimization planning-and-task-breakdown prototype quorum ready-for-production research resolving-merge-conflicts scaffold-exercises seat-shutdown security-and-hardening setup-pre-commit shipping-and-launch source-driven-development spec-driven-development split-to-prs tdd test-driven-development triad ubersicht-widget using-agent-skills wizard wrap-up writing-for-agents)

fm() { # $1 file $2 key -> value (first match in frontmatter)
  awk -v k="$2" 'NR==1&&$0!="---"{exit} NR>1&&$0=="---"{exit} NR>1{ if (index($0,k":")==1){ sub("^"k":[ ]*",""); print; exit } }' "$1"
}
fmkeys() { awk 'NR==1&&$0!="---"{exit} NR>1&&$0=="---"{exit} NR>1 && match($0,/^[A-Za-z_-]+:/){ printf "%s ", substr($0,1,RLENGTH-1) }' "$1"; }

typeset -A SEEN_ROOT SEEN_PATH ALLNAMES
# rows: name|root|dirpath|linktarget|skillmd exists|desc|dmi|keys
ROWS=()
for r in $ORDER; do
  root=${ROOTS[$r]}
  [[ -d $root ]] || continue
  for d in $root/*(/N) $root/*(@N); do
    name=${d:t}
    ALLNAMES[$name]=1
    link=""; [[ -L $d ]] && link=$(readlink -f "$d" 2>/dev/null || echo BROKEN)
    real=${link:-$d}
    smd="$real/SKILL.md"
    if [[ -f $smd ]]; then
      fname=$(fm "$smd" name); desc=$(fm "$smd" description | cut -c1-120 | tr '|' '/'); dmi=$(fm "$smd" disable-model-invocation); keys=$(fmkeys "$smd")
      ROWS+=("$name|$r|$d|$link|y|${fname:-—}|${desc:-—}|${dmi:-absent}|${keys:-—}")
    else
      ROWS+=("$name|$r|$d|$link|n|—|—|—|—")
    fi
  done
done

{
echo "# Skills — per-skill enumeration (Plumb, 2026-09-22)"
echo
echo "Generated by \`/Users/jowolff/code/agent-system-2.0/.tmp/phase2/enum-skills.sh\` (this file). Roots and priorities from \`INVENTORY.md:339,:347-350\`: omp p100 · claude p80 · plugin (newdle 0.2.171) p70 · plugin (claudex-loop 2.1.0, the second installed plugin per installed_plugins.json) p70 · agents p70; name dedupe by highest priority (\`OMP_SRC/capability/index.ts:241-249\`), real-path dedupe for symlinks (\`extensibility/skills.ts:264,:403\`)."
echo
echo "## 1. Raw listing — every entry under the four roots"
echo
echo "| name | root | entry (absolute) | symlink → | SKILL.md | frontmatter name | description (120c) | disable-model-invocation | frontmatter keys |"
echo "|---|---|---|---|---|---|---|---|---|"
for row in $ROWS; do echo "| ${row//|/ | } |"; done
echo
echo "## 2. Winner per name (what a session sees before hiding)"
echo
echo "| name | winner root | winner SKILL.md (absolute) | other copies | disable-model-invocation | in Plumb's block |"
echo "|---|---|---|---|---|---|"
typeset -A INBLOCK; for b in $BLOCK; do INBLOCK[$b]=1; done
VISIBLE=0; HIDDEN=(); NOSKILL=()
for name in ${(ok)ALLNAMES}; do
  winner=""; others=(); dmi="—"; wpath="—"
  for r in $ORDER; do
    for row in $ROWS; do
      IFS='|' read -r n rr d link has fn desc dm keys <<< "$row"
      [[ $n == $name && $rr == $r ]] || continue
      [[ $has == y ]] || { [[ -z $winner ]] && others+=("$d (no SKILL.md)"); continue }
      if [[ -z $winner ]]; then winner=$r; wpath="${link:-$d}/SKILL.md"; dmi=$dm; else others+=("$d"); fi
    done
  done
  if [[ -z $winner ]]; then NOSKILL+=($name); continue; fi
  ib=${INBLOCK[$name]:-0}; [[ $ib == 1 ]] && ib=y || ib=n
  if [[ $dmi == true ]]; then HIDDEN+=($name); else (( VISIBLE++ )); fi
  echo "| $name | $winner | $wpath | ${(j:, :)others:-—} | $dmi | $ib |"
done
echo
echo "## 3. Reconciliation against Plumb's \`<skills>\` block"
echo
echo "- Block count (copied from this seat's system prompt): ${#BLOCK}"
echo "- Distinct names on disk with a SKILL.md: $(( ${#${(@k)ALLNAMES}} - ${#NOSKILL} )) (of ${#${(@k)ALLNAMES}} entries)"
echo "- Hidden by \`disable-model-invocation: true\`: ${#HIDDEN} — ${(j:, :)HIDDEN}"
echo "- Visible after hiding: $VISIBLE"
echo "- Entries with no SKILL.md (empty dir or broken link): ${#NOSKILL} — ${(j:, :)NOSKILL:-none}"
MISSING=(); EXTRA=()
for b in $BLOCK; do [[ -n ${ALLNAMES[$b]:-} ]] || MISSING+=($b); done
for name in ${(ok)ALLNAMES}; do [[ -n ${INBLOCK[$name]:-} ]] && continue; [[ " ${NOSKILL[*]} " == *" $name "* ]] && continue; EXTRA+=($name); done
echo "- In block but on no root: ${#MISSING} — ${(j:, :)MISSING:-none}"
echo "- On disk with SKILL.md but not in block: ${#EXTRA} — ${(j:, :)EXTRA:-none}"
echo
echo "## 4. \`/Users/jowolff/.claude/skills\` recount (settles INVENTORY.md:161 vs :347)"
echo
c=/Users/jowolff/.claude/skills
realdirs=(); links=(); brokenlinks=(); emptydirs=()
for d in $c/*(/N); do if [[ -f $d/SKILL.md ]]; then realdirs+=(${d:t}); else emptydirs+=(${d:t}); fi; done
for d in $c/*(@N); do if [[ -e $d ]]; then links+=(${d:t}); else brokenlinks+=(${d:t}); fi; done
echo "- \`ls -la $c\` at $(date -u +%FT%TZ): real dirs with SKILL.md ${#realdirs}; real dirs without SKILL.md ${#emptydirs} (${(j:, :)emptydirs:-none}); symlinks resolving ${#links}; symlinks broken ${#brokenlinks} (${(j:, :)brokenlinks:-none}); total entries $(( ${#realdirs} + ${#emptydirs} + ${#links} + ${#brokenlinks} ))"
echo "- real dirs: ${(j:, :)realdirs}"
echo "- \`/Users/jowolff/.agents/skills\` dirs: $(ls -d /Users/jowolff/.agents/skills/*/ 2>/dev/null | wc -l | tr -d ' ')"
echo "- symlink targets outside \`/Users/jowolff/.agents/skills\`: $(for d in $c/*(@N); do t=$(readlink -f $d); [[ $t == /Users/jowolff/.agents/skills/* ]] || echo "${d:t}→$t"; done | tr '\n' ' ')"
} > $OUT
echo "wrote $OUT ($(wc -l < $OUT) lines)"
